'use strict';
// Regenerates docs/COMMANDS.md from the live command registry.   node scripts/gen-commands-doc.js
const fs = require('node:fs');
const path = require('node:path');
const { loadCommands } = require('../src/framework/registry');
const { label } = require('../src/framework/permissionNames');

const reg = loadCommands(path.join(__dirname, '../src/commands'));
const groups = new Map();
for (const c of reg.all) { if (!groups.has(c.category)) groups.set(c.category, []); groups.get(c.category).push(c); }
const opt = (o) => `${o.required ? '<' : '['}${o.name}${o.rest ? '...' : ''}${o.required ? '>' : ']'}`;
let md = '# Command reference\n\n_Generated by `node scripts/gen-commands-doc.js`; do not edit by hand._\n\n`/` = slash command, `!` = prefix command (default prefix `!`, changeable with `setprefix`).\n';
for (const [cat, list] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
  md += `\n## ${cat[0].toUpperCase()}${cat.slice(1)}\n\n| Command | Where | Who | Description |\n|---|---|---|---|\n`;
  for (const c of list) {
    const where = [c.slash ? '`/`' : '', c.prefix ? `\`!\`${c.prefixNames ? ` as \`!${c.prefixNames.join(' !')}\`` : ''}` : ''].filter(Boolean).join(' ');
    const who = c.ownerOnly ? 'Bot owner' : c.userPermissions.length ? c.userPermissions.map(label).join(' + ') : 'Everyone';
    if (c.subcommands) {
      for (const [n, s] of Object.entries(c.subcommands)) {
        const sw = s.userPermissions?.length ? s.userPermissions.map(label).join(' + ') : who;
        md += `| \`${c.name} ${n}${s.options.length ? ' ' + s.options.map(opt).join(' ') : ''}\` | ${where} | ${sw} | ${s.description} |\n`;
      }
    } else md += `| \`${c.name}${c.options.length ? ' ' + c.options.map(opt).join(' ') : ''}\` | ${where} | ${who} | ${c.description} |\n`;
  }
}
fs.writeFileSync(path.join(__dirname, '../docs/COMMANDS.md'), md);
console.log(`wrote docs/COMMANDS.md (${reg.all.length} top-level commands)`);
